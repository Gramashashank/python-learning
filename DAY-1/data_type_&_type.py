#-----DATA TYPE-----#

#----1.INT-----#

age=18
print(age)
#---O/P----#
#---18----#

#----type of int-----#

print(type(age))
#---O/P----#
#---<class 'int'>----#

#---2.FLOAT-----#
height=5.9
print(height)
#---O/P----#
#---5.9----#

#---type of float-----#
print(type(height))
#---O/P----#
#---<class 'float'>----#

#---3.STRING-----#
name="shashank"
print(name)
#---O/P----#
#---shashank----#

#---type of string-----#
print(type(name))
#---O/P----#
#---<class 'str'>----#

#---4.BOOLEAN-----#
is_student=True
print(is_student)
#---O/P----#
#---True----#

#---type of boolean-----#
print(type(is_student))
#---O/P----#
#---<class 'bool'>----#

#----ADDITIONAL DATA TYPES-----#

